import time
from sqlalchemy import text
from sqlalchemy.orm import Session

from database import SessionLocal


# ============================================================
# Execute SQL Query
# ============================================================

def execute_query(sql: str, params: dict):
    """
    Executes parameterized SQL on PostgreSQL.

    Parameters
    ----------
    sql : str
        SQL generated by sql_compiler.py

    params : dict
        Named SQLAlchemy parameters

    Returns
    -------
    dict
    """

    db: Session = SessionLocal()

    start = time.perf_counter()

    try:

        # ----------------------------------------------------
        # Execute Query
        # ----------------------------------------------------

        result = db.execute(
            text(sql),
            params
        )

        rows = result.mappings().all()

        execution_time = round(
            time.perf_counter() - start,
            6
        )

        results = [
            dict(row)
            for row in rows
        ]

        # ----------------------------------------------------
        # Empty Result
        # ----------------------------------------------------

        if not results:

            return {

                "success": True,

                "execution_time": execution_time,

                "count": 0,

                "sql": sql,

                "params": params,

                "Results": [],

                "message": "No matching companies found."

            }

        # ----------------------------------------------------
        # Success
        # ----------------------------------------------------

        return {

            "success": True,

            "execution_time": execution_time,

            "count": len(results),

            "sql": sql,

            "params": params,

            "Results": results

        }

    except Exception as e:

        db.rollback()

        return {

            "success": False,

            "execution_time": round(
                time.perf_counter() - start,
                6
            ),

            "sql": sql,

            "params": params,

            "error": str(e)

        }

    finally:

        db.close()